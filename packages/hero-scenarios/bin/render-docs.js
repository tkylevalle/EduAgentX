#!/usr/bin/env node
'use strict';

// Writes docs/sprint-5/hero-scenarios.md from the catalog so the document
// cannot drift from what the verifier checks.
const fs = require('node:fs');
const path = require('node:path');
const { SCENARIOS, LIVE_BOUNDS } = require('../src');

const out = path.resolve(__dirname, '../../../docs/sprint-5/hero-scenarios.md');
const lines = [];
lines.push('# Sprint 5 hero scenarios (issue 34)', '');
lines.push('This file is generated by `npm run docs` in `packages/hero-scenarios`. Edit `src/scenarios.js`, not this file.', '');
lines.push('Every scenario runs with an isolated test Agent Learner, simulated tools, test keys and a reset that only removes records tagged with its own runId. No scenario has a real external side effect.', '');
lines.push('## The nine demonstrations', '');
lines.push('| # | Scenario | Type | Evidence mode | Learner | Depends on |', '|---|---|---|---|---|---|');
for (const s of SCENARIOS) {
  lines.push(`| ${s.number} | ${s.title} | ${s.kind} | ${s.evidenceMode} | ${s.learner ? s.learner.identity : 'none'} | ${s.dependencies.length ? s.dependencies.join('; ') : 'none'} |`);
}
lines.push('', '## Fault declarations', '');
lines.push('Each injected failure declares its forbidden outcome, minimum safe blast radius, Safe State, retry or fallback, Assurance Incident and recovery condition.', '');
for (const s of SCENARIOS.filter((item) => item.injectedFault)) {
  const f = s.injectedFault;
  lines.push(`### ${s.number}. ${s.title}`, '');
  lines.push('| Field | Declaration |', '|---|---|');
  lines.push(`| Injected fault | ${f.name}. ${f.injection} |`);
  lines.push(`| Forbidden outcome | ${f.forbiddenOutcome} |`);
  lines.push(`| Minimum safe blast radius | ${f.minimumSafeBlastRadius} |`);
  lines.push(`| Safe State | ${f.safeState.state}. ${f.safeState.description} |`);
  lines.push(`| Retry or fallback | ${f.retryFallback} |`);
  lines.push(`| Assurance Incident | ${f.assuranceIncident.category}, severity ${f.assuranceIncident.severity}. Cause: ${f.assuranceIncident.cause}. Detected by: ${f.assuranceIncident.detection}. |`);
  lines.push(`| Recovery condition | ${f.recoveryCondition} |`, '');
}
lines.push('## Clean and refusal demonstrations', '');
for (const s of SCENARIOS.filter((item) => !item.injectedFault)) {
  lines.push(`### ${s.number}. ${s.title}`, '', `Expected: ${s.expected}`, '');
}
lines.push('## Optional live runs', '');
lines.push(`Any live run is bounded by ${LIVE_BOUNDS.maxCalls} calls, ${LIVE_BOUNDS.maxTokens} tokens, ${LIVE_BOUNDS.maxRuntimeSeconds} seconds and ${LIVE_BOUNDS.maxSpendUsd} USD. These are proposed values and the team can change them. Each live run has a verified replay alternative that is labelled replay, never live.`, '');
lines.push('| Scenario | Replay executor | Fixture |', '|---|---|---|');
for (const s of SCENARIOS.filter((item) => item.live)) {
  lines.push(`| ${s.title} | ${s.live.replayAlternative.executorIdentity} | ${s.live.replayAlternative.fixtureRef} (${s.live.replayAlternative.approval}) |`);
}
lines.push('', '## Evidence required per scenario', '');
lines.push('| Scenario | Artifacts that must be retained |', '|---|---|');
for (const s of SCENARIOS) lines.push(`| ${s.title} | ${s.evidenceRequired.join(', ')} |`);
lines.push('');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)}`);
